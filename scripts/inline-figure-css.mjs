/*
 * Wraps remotion/figures.css into a TypeScript module exporting it as a string.
 *
 * The video bundler treats `import './x.css'` as a side effect, not a value, and
 * the figures need their stylesheet injected into the composition as text. This
 * keeps the CSS a generated artifact of the game repository rather than
 * something hand-maintained here.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync('remotion/figures.css', 'utf8');
const escaped = css.replaceAll('`', '\\`').replaceAll('${', '\\${');
writeFileSync(
  'remotion/figures-css.ts',
  `/*
 * GENERATED by scripts/inline-figure-css.mjs. Do not edit by hand.
 * Source: remotion/figures.css, itself exported from the game repository by
 * scripts/export-help-figure-css.mjs --dark.
 */
export const figureCss = String.raw\`${escaped}\`;
`,
);
process.stdout.write('WROTE remotion/figures-css.ts\n');
